const fs = require("node:fs"),
  path = require("node:path"),
  crypto = require("node:crypto");
const root = path.resolve(__dirname, ".."),
  out = path.join(root, "dist"),
  pub = path.join(root, "public/build");
const scripts = [
  "src/game/engine.js",
  "src/game/events.js",
  "src/game/save.js",
  "src/content/events.js",
  "src/content/characters.js",
  "src/audio.js",
  "src/table-camera.js",
  "src/motion.js",
  "src/select.js",
  "src/main.js",
];
const styles = ["src/styles/main.css", "src/styles/viewport.css", "src/styles/setup.css", "src/styles/select.css"];
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
function walk(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((e) =>
      e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)],
    );
}
const assets = walk(path.join(root, "public/assets"))
  .filter((p) => !p.includes("/originals/"))
  .sort();
const version = JSON.parse(read("package.json")).version;
const hash = crypto.createHash("sha256");
hash.update(version);
for (const file of [
  ...scripts,
  ...styles,
  "src/shell.html",
  "src/bootstrap.js",
  "src/service-worker.js",
])
  hash.update(file).update(read(file));
for (const file of assets)
  hash.update(path.relative(root, file)).update(fs.readFileSync(file));
const id = hash.digest("hex").slice(0, 16);
const build = {
  version,
  id,
  html: `index-${id}.html`,
  js: `public/build/app-${id}.js`,
  css: `public/build/app-${id}.css`,
};
fs.mkdirSync(pub, { recursive: true });
// Keep only the current generated publication; previous running tabs retain their installed release cache.
for (const f of fs.readdirSync(pub))
  if (/^app-[a-f0-9]+\.(js|css)$/.test(f)) fs.unlinkSync(path.join(pub, f));
const js = scripts.map(read).join("\n;\n");
const css = styles
  .map(read)
  .join("\n")
  .replace(/url\((['"]?)([^)'"?]+)\1\)/g, (all, quote, url) =>
    url.startsWith("data:") ? all : `url(${quote}${url}?v=${id}${quote})`,
  );
fs.writeFileSync(path.join(root, build.js), js);
fs.writeFileSync(path.join(root, build.css), css);
const inline = `<script>window.VahtaBuild=${JSON.stringify(build)};\n${read("src/bootstrap.js")}</script>`;
fs.writeFileSync(
  path.join(root, "index.html"),
  "<!-- Generated by npm run build; edit src/shell.html, not this file. -->\n" +
    read("src/shell.html")
      .replace("__BUILD_ID__", id)
      .replace("<!--BOOT-->", inline),
);
fs.writeFileSync(
  path.join(root, "version.json"),
  JSON.stringify(build, null, 2) + "\n",
);
for (const file of fs.readdirSync(root))
  if (/^index-[a-f0-9]{16}\.html$/.test(file))
    fs.unlinkSync(path.join(root, file));
fs.copyFileSync(path.join(root, "index.html"), path.join(root, build.html));
const files = [
  "index.html",
  build.html,
  build.js,
  build.css,
  ...assets.map(
    (p) => path.relative(root, p).split(path.sep).join("/") + "?v=" + id,
  ),
];
fs.writeFileSync(
  path.join(root, "sw.js"),
  read("src/service-worker.js")
    .replace("__BUILD__", JSON.stringify(build))
    .replace("__FILES__", JSON.stringify(files)),
);
fs.writeFileSync(path.join(root, ".nojekyll"), "");
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
for (const p of [
  "index.html",
  build.html,
  "version.json",
  "sw.js",
  ".nojekyll",
  "src",
  "public",
])
  fs.cpSync(path.join(root, p), path.join(out, p), {
    recursive: true,
    filter: (source) => !source.includes("/originals"),
  });
console.log(`Offline + GitHub Pages build: ${version} (${id})`);
